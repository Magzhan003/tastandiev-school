-- Create the whole queue in one admin action. Each question = 24 hours.
create or replace function public.create_daily_quiz_batch(p_start_at timestamptz,p_questions jsonb)
returns bigint
language plpgsql security definer set search_path=public as $$
declare batch_id bigint; actual_start timestamptz; last_end timestamptz; item jsonb; i integer:=0;
begin
  if auth.uid() is null then raise exception 'admin authentication required'; end if;
  if jsonb_typeof(p_questions)<>'array' or jsonb_array_length(p_questions)<1 then raise exception 'questions are required'; end if;
  select max(ends_at) into last_end from public.quiz_questions where ends_at is not null and published_at is null;
  actual_start:=greatest(coalesce(p_start_at,now()),coalesce(last_end,coalesce(p_start_at,now())));
  insert into public.quiz_batches(title,start_at) values('Күнделікті викторина',actual_start) returning id into batch_id;
  for item in select value from jsonb_array_elements(p_questions) loop
    i:=i+1;
    insert into public.quiz_questions(batch_id,sequence_no,question,option_a,option_b,option_c,option_d,correct_option,starts_at,ends_at,published_at,xp_applied)
    values(batch_id,i,item->>'question',item->>'option_a',item->>'option_b',item->>'option_c',item->>'option_d',lower(item->>'correct_option'),actual_start+((i-1)*interval '24 hours'),actual_start+(i*interval '24 hours'),null,false);
  end loop;
  return batch_id;
end;
$$;
grant execute on function public.create_daily_quiz_batch(timestamptz,jsonb) to authenticated;

