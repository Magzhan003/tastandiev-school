-- Daily quiz: class must exist in class_limits and each class has a fixed number of attempts per question.
create or replace function public.submit_daily_quiz(p_question_id bigint,p_student_name text,p_class_name text,p_answer text)
returns table(score integer,total integer)
language plpgsql security definer set search_path=public as $$
declare q record; norm_name text; norm_class text; lim integer; used integer; final_score integer;
begin
  perform public.sync_daily_quiz_state();
  if nullif(trim(p_student_name),'') is null or nullif(trim(p_class_name),'') is null then raise exception 'name and class are required'; end if;
  norm_name:=lower(regexp_replace(trim(p_student_name),'\s+','','g'));
  norm_class:=translate(upper(regexp_replace(trim(p_class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ');
  select attempt_limit into lim from public.class_limits where translate(upper(regexp_replace(trim(class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ')=norm_class;
  if lim is null then raise exception 'class is not configured'; end if;
  select * into q from public.quiz_questions where id=p_question_id and starts_at<=now() and now()<ends_at and published_at is null;
  if q.id is null then raise exception 'quiz is not active'; end if;
  select count(*) into used from public.quiz_attempts where question_id=p_question_id and translate(upper(regexp_replace(trim(class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ')=norm_class;
  if used >= lim then raise exception 'class limit reached'; end if;
  if exists(select 1 from public.quiz_attempts a where a.question_id=p_question_id and lower(regexp_replace(trim(a.student_name),'\s+','','g'))=norm_name and translate(upper(regexp_replace(trim(a.class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ')=norm_class) then raise exception 'already submitted'; end if;
  final_score:=case when lower(trim(p_answer))=lower(q.correct_option) then 1 else 0 end;
  insert into public.quiz_attempts(student_name,class_name,score,total,question_id,xp_applied) values(trim(p_student_name),trim(p_class_name),final_score,1,p_question_id,false);
  return query select final_score,1;
end; $$;
grant execute on function public.submit_daily_quiz(bigint,text,text,text) to anon,authenticated;

-- Battle: fixed class capacity per battle. Every attempt consumes one slot, even if the name is wrong.
create or replace function public.start_battle_attempt(p_battle_id bigint,p_student_name text,p_class_name text)
returns table(attempt_id bigint,started_at timestamptz)
language plpgsql security definer set search_path=public as $$
declare b record; existing record; norm_name text; norm_class text; lim integer; used integer; allowed boolean;
begin
  if nullif(trim(p_student_name),'') is null or nullif(trim(p_class_name),'') is null then raise exception 'name and class are required'; end if;
  select * into b from public.battles where id=p_battle_id;
  if b.id is null then raise exception 'battle not found'; end if;
  if now() < b.battle_date then raise exception 'battle is not active'; end if;
  if now() >= b.battle_date + interval '30 minutes' then raise exception 'battle is over'; end if;
  norm_name:=lower(regexp_replace(trim(p_student_name),'\s+','','g'));
  norm_class:=translate(upper(regexp_replace(trim(p_class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ');
  select attempt_limit into lim from public.class_limits where translate(upper(regexp_replace(trim(class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ')=norm_class;
  if lim is null then raise exception 'class is not configured'; end if;
  allowed:=exists(select 1 from unnest(string_to_array(regexp_replace(coalesce(b.classes,''),'\s*,\s*',','),',')) x where translate(upper(trim(x)),'ABEKMHOPCTXY','АВЕКМНОРСТХУ')=norm_class);
  if not allowed then raise exception 'class is not participating'; end if;
  select * into existing from public.battle_attempts where battle_id=p_battle_id and lower(regexp_replace(trim(student_name),'\s+','','g'))=norm_name and translate(upper(regexp_replace(trim(class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ')=norm_class limit 1;
  if existing.id is not null then
    if existing.completed then raise exception 'already submitted'; end if;
    return query select existing.id,existing.started_at; return;
  end if;
  select count(*) into used from public.battle_attempts where battle_id=p_battle_id and translate(upper(regexp_replace(trim(class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ')=norm_class;
  if used >= lim then raise exception 'class limit reached'; end if;
  insert into public.battle_attempts(battle_id,student_name,class_name,score,total,started_at,completed) values(p_battle_id,trim(p_student_name),trim(p_class_name),0,(select count(*) from public.battle_questions where battle_id=p_battle_id),b.battle_date,false) returning id,started_at into attempt_id,started_at;
  return next;
end; $$;
grant execute on function public.start_battle_attempt(bigint,text,text) to anon,authenticated;

