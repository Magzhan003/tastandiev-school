-- NOTE: an earlier draft of start_battle_attempt used to live here, but its
-- RETURNS TABLE column was named "id" while the final version below (added
-- with the class-limits feature) names it "attempt_id". Since PostgreSQL
-- refuses "CREATE OR REPLACE FUNCTION" when the return type changes, having
-- both in one script would abort the whole migration partway through with
-- "cannot change return type of existing function". Removed the dead draft
-- here so only the working version (further down) is ever created.


create or replace function public.submit_battle_attempt(p_attempt_id bigint,p_answers jsonb)
returns table(score integer,total integer,duration_seconds integer)
language plpgsql security definer set search_path=public as $$
declare a record; q record; ans jsonb; s integer:=0; total_q integer:=0; dur integer;
begin
  select * into a from public.battle_attempts where id=p_attempt_id for update;
  if a.id is null then raise exception 'attempt not found'; end if;
  if a.completed then return query select a.score,a.total,coalesce(a.duration_seconds,0); return; end if;
  dur:=extract(epoch from (now()-a.started_at))::integer;
  if dur>1800 then
    update public.battle_attempts set completed=true,finished_at=a.started_at+interval '30 minutes',duration_seconds=1800 where id=a.id;
    raise exception 'time expired';
  end if;
  for q in select * from public.battle_questions where battle_id=a.battle_id order by created_at,id loop
    total_q:=total_q+1;
    select value into ans from jsonb_array_elements(coalesce(p_answers,'[]'::jsonb)) where (value->>'question_id')::bigint=q.id limit 1;
    if ans is not null and lower(ans->>'answer')=lower(q.correct_option) then s:=s+1; end if;
  end loop;
  dur:=extract(epoch from (now()-a.started_at))::integer;
  update public.battle_attempts set score=s,total=total_q,completed=true,finished_at=now(),duration_seconds=dur where id=a.id;
  return query select s,total_q,dur;
end;
$$;
grant execute on function public.submit_battle_attempt(bigint,jsonb) to anon,authenticated;

