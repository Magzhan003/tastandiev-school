create or replace function public.submit_quest_attempt(p_quest_id bigint,p_student_name text,p_class_name text,p_answers jsonb)
returns table(score integer,total integer)
language plpgsql security definer set search_path=public as $$
declare q record; ans jsonb; s integer:=0; t integer:=0; norm_name text; norm_class text; final_score integer;
begin
  if nullif(trim(p_student_name),'') is null or nullif(trim(p_class_name),'') is null then raise exception 'name and class are required'; end if;
  if not exists(select 1 from public.quests where id=p_quest_id and published=true) then raise exception 'quest is not active'; end if;
  norm_name:=lower(regexp_replace(trim(p_student_name),'\s+','','g'));
  norm_class:=translate(upper(regexp_replace(trim(p_class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ');
  if exists(select 1 from public.quest_attempts where quest_id=p_quest_id and lower(regexp_replace(trim(student_name),'\s+','','g'))=norm_name and translate(upper(regexp_replace(trim(class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ')=norm_class) then raise exception 'already submitted'; end if;
  for q in select * from public.quest_questions where quest_id=p_quest_id order by sequence_no,id loop
    t:=t+1;
    select value into ans from jsonb_array_elements(coalesce(p_answers,'[]'::jsonb)) where (value->>'question_id')::bigint=q.id limit 1;
    if ans is not null and lower(ans->>'answer')=lower(q.correct_option) then s:=s+1; end if;
  end loop;
  insert into public.quest_attempts(quest_id,student_name,class_name,score,total) values(p_quest_id,trim(p_student_name),trim(p_class_name),s,t);
  if s>0 then
    insert into public.class_xp(class_name,xp,updated_at) values(norm_class,s,now())
    on conflict(class_name) do update set xp=public.class_xp.xp+s,updated_at=now();
    -- Reuse the student-rating stream so quest points appear in the top-5 list.
    insert into public.quiz_attempts(student_name,class_name,score,total,question_id,xp_applied)
    values(trim(p_student_name),trim(p_class_name),s,t,null,true);
  end if;
  return query select s,t;
exception when unique_violation then raise exception 'already submitted';
end; $$;
grant execute on function public.submit_quest_attempt(bigint,text,text,jsonb) to anon, authenticated;

