-- ================================================================
-- PHASE 1: secure "read → quest → verify → XP" pipeline.
-- Previously a student could insert/update book_progress directly from
-- the browser, marking any book "read" with no quest check at all.
-- From now on: the client can only DECLARE intent to read (which requires
-- a quest to already exist for that book) and SUBMIT quest answers; the
-- server alone decides whether the book becomes "verified" and whether
-- XP is granted — and only once per student per book, ever.
-- ================================================================

alter table public.book_progress add column if not exists verified boolean not null default false;
alter table public.book_progress add column if not exists xp_awarded boolean not null default false;
alter table public.book_progress add column if not exists verified_at timestamptz;

-- Students can no longer write to book_progress directly — only read it.
-- (SECURITY DEFINER functions below bypass RLS to do the actual writes.)
drop policy if exists "Students can mark own books read" on public.book_progress;
drop policy if exists "Students can update own book progress" on public.book_progress;
revoke insert, update on public.book_progress from authenticated;

-- Step 1: student presses "Мен оқыдым" — this only "declares" intent and
-- requires a quest to already be linked to the book, otherwise it fails
-- with a clear reason the UI can show ("no_quest").
create or replace function public.declare_book_read(p_book_id bigint)
returns table(quest_id bigint, already_verified boolean)
language plpgsql security definer set search_path=public as $$
declare sid bigint; qid bigint; bp record;
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  select id into sid from public.student_profiles where auth_user_id=auth.uid();
  if sid is null then raise exception 'student profile not linked'; end if;

  select id into qid from public.quests where book_id=p_book_id and published=true order by created_at desc limit 1;
  if qid is null then raise exception 'no_quest'; end if;

  select * into bp from public.book_progress where student_id=sid and book_id=p_book_id;
  if bp.id is null then
    insert into public.book_progress(student_id,book_id,marked_read_at) values(sid,p_book_id,now());
    return query select qid, false;
  else
    return query select qid, bp.verified;
  end if;
end; $$;
grant execute on function public.declare_book_read(bigint) to authenticated;

-- Step 2: student submits answers for a book-linked quest. The server
-- grades it, and only marks the book "verified" + awards +50 XP the
-- FIRST time a student passes — repeat attempts never re-award XP.
-- Passing bar: at least 60% correct (rounded up).
create or replace function public.submit_book_quest_attempt(p_quest_id bigint, p_answers jsonb)
returns table(score integer, total integer, passed boolean, xp_awarded integer)
language plpgsql security definer set search_path=public as $$
declare
  sid bigint; sp record; qrow record; bp record; q record; ans jsonb;
  s integer:=0; t integer:=0; did_pass boolean; awarded integer:=0; norm_class text;
begin
  if auth.uid() is null then raise exception 'login required'; end if;
  select * into sp from public.student_profiles where auth_user_id=auth.uid();
  if sp.id is null then raise exception 'student profile not linked'; end if;
  sid := sp.id;

  select * into qrow from public.quests where id=p_quest_id and published=true;
  if qrow.id is null then raise exception 'quest is not active'; end if;
  if qrow.book_id is null then raise exception 'not a book quest'; end if;

  select * into bp from public.book_progress where student_id=sid and book_id=qrow.book_id;
  if bp.id is null then raise exception 'book not declared as read yet'; end if;

  for q in select * from public.quest_questions where quest_id=p_quest_id order by sequence_no,id loop
    t:=t+1;
    select value into ans from jsonb_array_elements(coalesce(p_answers,'[]'::jsonb)) where (value->>'question_id')::bigint=q.id limit 1;
    if ans is not null and lower(ans->>'answer')=lower(q.correct_option) then s:=s+1; end if;
  end loop;
  if t=0 then raise exception 'quest has no questions'; end if;

  did_pass := s >= ceil(t*0.6);
  norm_class := translate(upper(regexp_replace(trim(sp.class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ');

  insert into public.quest_attempts(quest_id,student_name,class_name,score,total)
  values(p_quest_id,sp.full_name,sp.class_name,s,t);

  if did_pass and not bp.xp_awarded then
    update public.book_progress set verified=true, xp_awarded=true, verified_at=now() where id=bp.id;
    insert into public.class_xp(class_name,xp,updated_at) values(norm_class,50,now())
      on conflict(class_name) do update set xp=public.class_xp.xp+50, updated_at=now();
    insert into public.quiz_attempts(student_name,class_name,score,total,question_id,xp_applied)
      values(sp.full_name,sp.class_name,50,50,null,true);
    awarded := 50;
  elsif did_pass then
    -- Already verified before: let them retake for practice, but never pay twice.
    awarded := 0;
  end if;

  return query select s, t, did_pass, awarded;
end; $$;
grant execute on function public.submit_book_quest_attempt(bigint,jsonb) to authenticated;

