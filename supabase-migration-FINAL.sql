create or replace function public.finalize_battle_rewards(p_battle_id bigint)
returns table(winner_class text,best_student text,best_class text)
language plpgsql security definer set search_path=public as $$
declare b record; r record; top record; norm_class text;
begin
  select * into b from public.battles where id=p_battle_id for update;
  if b.id is null then raise exception 'battle not found'; end if;
  if now() < b.battle_date + interval '30 minutes' then raise exception 'battle is not finished'; end if;
  if not b.rewards_applied then
    update public.battle_attempts set completed=true,finished_at=b.battle_date+interval '30 minutes',duration_seconds=1800 where battle_id=p_battle_id and completed=false;
    select norm_cls, sum(total_score) total_score, min(label) label into r
    from (select translate(upper(regexp_replace(trim(class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ') norm_cls, sum(score) total_score, min(class_name) label
          from public.battle_attempts where battle_id=p_battle_id and completed=true group by 1) x
    group by norm_cls order by sum(total_score) desc, norm_cls asc limit 1;
    select * from public.battle_attempts where battle_id=p_battle_id and completed=true order by score desc,duration_seconds asc,id asc limit 1 into top;
    if r.norm_cls is not null then
      norm_class:=r.norm_cls;
      insert into public.class_xp(class_name,xp,updated_at) values(norm_class,50,now()) on conflict(class_name) do update set xp=public.class_xp.xp+50,updated_at=now();
    end if;
    if top.student_name is not null then
      insert into public.quiz_attempts(student_name,class_name,score,total,question_id,xp_applied) values(trim(top.student_name),trim(top.class_name),10,10,null,true);
    end if;
    update public.battles set rewards_applied=true where id=p_battle_id;
  end if;
  select x.label into winner_class from (select translate(upper(regexp_replace(trim(class_name),'\s+','','g')),'ABEKMHOPCTXY','АВЕКМНОРСТХУ') norm_cls, min(class_name) label, sum(score) total_score from public.battle_attempts where battle_id=p_battle_id and completed=true group by 1) x order by x.total_score desc,x.norm_cls asc limit 1;
  select student_name,class_name from public.battle_attempts where battle_id=p_battle_id and completed=true order by score desc,duration_seconds asc,id asc limit 1 into best_student,best_class;
  return next;
end; $$;
grant execute on function public.finalize_battle_rewards(bigint) to anon, authenticated;

