-- Archive expired questions and award XP exactly once when their 24h window ends.
create or replace function public.sync_daily_quiz_state()
returns void
language plpgsql
security definer
set search_path=public
as $$
declare q record; a record; norm_class text;
begin
  for q in select id from public.quiz_questions where ends_at is not null and ends_at <= now() and published_at is null order by ends_at,id loop
    update public.quiz_questions set published_at=ends_at where id=q.id and published_at is null;
    for a in select id,class_name,score from public.quiz_attempts where question_id=q.id and xp_applied=false loop
      if a.score=1 then
        norm_class:=translate(upper(regexp_replace(trim(a.class_name), '\s+', '', 'g')), 'ABEKMHOPCTXY', 'АВЕКМНОРСТХУ');
        insert into public.class_xp(class_name,xp,updated_at) values(norm_class,1,now())
        on conflict(class_name) do update set xp=public.class_xp.xp+1,updated_at=now();
      end if;
      update public.quiz_attempts set xp_applied=true where id=a.id;
    end loop;
  end loop;
end;
$$;
grant execute on function public.sync_daily_quiz_state() to anon, authenticated;

create or replace function public.get_current_daily_quiz()
returns table(id bigint,batch_id bigint,sequence_no integer,question text,option_a text,option_b text,option_c text,option_d text,starts_at timestamptz,ends_at timestamptz)
language plpgsql security definer set search_path=public as $$
begin
  perform public.sync_daily_quiz_state();
  return query select q.id,q.batch_id,q.sequence_no,q.question,q.option_a,q.option_b,q.option_c,q.option_d,q.starts_at,q.ends_at
  from public.quiz_questions q
  where q.starts_at is not null and q.starts_at <= now() and now() < q.ends_at and q.published_at is null
  order by q.starts_at desc,q.id desc limit 1;
end;
$$;
grant execute on function public.get_current_daily_quiz() to anon, authenticated;

